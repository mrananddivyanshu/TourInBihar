let currentLanguage = localStorage.getItem('dlb_language') || 'en';

function getTranslation(key) {
  const lang = currentLanguage in TRANSLATIONS ? currentLanguage : 'en';
  return TRANSLATIONS[lang][key] || TRANSLATIONS['en'][key] || key;
}

function setLanguage(lang) {
  if (lang !== 'en' && lang !== 'hi') lang = 'en';
  currentLanguage = lang;
  localStorage.setItem('dlb_language', lang);
  document.documentElement.lang = lang;
  applyTranslations();
  if (typeof renderAllViews === 'function') {
    renderAllViews();
  }
}

function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const trans = getTranslation(key);
    if (trans) {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = trans;
      } else {
        el.textContent = trans;
      }
    }
  });

  // Update language toggle button visual indicator
  const langToggleBtn = document.getElementById('lang-toggle-btn');
  if (langToggleBtn) {
    langToggleBtn.innerHTML = currentLanguage === 'en' 
      ? `<span>हिन्दी</span>` 
      : `<span>English</span>`;
    langToggleBtn.setAttribute('title', currentLanguage === 'en' ? 'हिन्दी में बदलें' : 'Switch to English');
  }
}

